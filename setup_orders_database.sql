CREATE OR REPLACE FUNCTION public.calculate_shipping(
    from_cep TEXT,
    to_cep TEXT,
    items_count INT,
    total_value NUMERIC
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    me_token TEXT;
    me_sandbox TEXT;
    api_url TEXT := 'https://www.melhorenvio.com.br/api/v2/me/shipment/calculate';
    req_body TEXT;
    response_status INT;
    response_content TEXT;
BEGIN
    -- Obter o token do Melhor Envio das configurações da loja
    SELECT value INTO me_token FROM public.store_settings WHERE key = 'melhor_envio_token';
    SELECT value INTO me_sandbox FROM public.store_settings WHERE key = 'melhor_envio_sandbox';
    
    IF me_token IS NULL OR me_token = '' THEN
        RETURN jsonb_build_object('error', 'Token do Melhor Envio não configurado.');
    END IF;

    -- Alternar entre ambiente de produção e testes sandbox
    IF me_sandbox = 'true' THEN
        api_url := 'https://sandbox.melhorenvio.com.br/api/v2/me/shipment/calculate';
    END IF;

    -- Montar o corpo da requisição com tamanho padrão estimado com base na quantidade de produtos
    req_body := json_build_object(
        'from', json_build_object('postal_code', replace(from_cep, '-', '')),
        'to', json_build_object('postal_code', replace(to_cep, '-', '')),
        'products', json_build_array(
            json_build_object(
                'id', 'pacote_estimado',
                'width', 15,
                'height', 15,
                'length', 20,
                'weight', 0.4 * items_count,
                'insurance_value', total_value,
                'quantity', 1
            )
        )
    )::text;

    -- Executar chamada HTTP POST
    SELECT 
        status, 
        content 
    INTO 
        response_status, 
        response_content
    FROM http((
        'POST',
        api_url,
        ARRAY[
            http_header('Authorization', 'Bearer ' || me_token),
            http_header('Content-Type', 'application/json'),
            http_header('Accept', 'application/json')
        ],
        'application/json',
        req_body
    )::http_request);

    -- Verificar se a chamada retornou sucesso
    IF response_status >= 200 AND response_status < 300 THEN
        RETURN response_content::jsonb;
    ELSE
        RETURN jsonb_build_object(
            'error', 'Erro ao consultar a API do Melhor Envio',
            'status', response_status,
            'response', response_content::jsonb
        );
    END IF;
EXCEPTION WHEN OTHERS THEN
    RETURN jsonb_build_object('error', SQLERRM);
END;
$$;
