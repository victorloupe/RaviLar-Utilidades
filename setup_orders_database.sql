-- 1. Criar a tabela de Pedidos (orders)
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL, -- Vincula ao Auth do Supabase se logado
    status TEXT DEFAULT 'Pendente' NOT NULL, -- Pendente, Pago, Separando, Em Transporte, Entregue, Cancelado
    payment_method TEXT NOT NULL, -- Pix, Cartão de Crédito
    payment_status TEXT DEFAULT 'Pendente' NOT NULL, -- Pendente, Pago, Estornado, Recusado
    total_amount NUMERIC NOT NULL,
    shipping_fee NUMERIC DEFAULT 0.0 NOT NULL,
    shipping_method TEXT DEFAULT 'Envio' NOT NULL,
    client_name TEXT NOT NULL,
    client_phone TEXT NOT NULL,
    client_email TEXT,
    cep TEXT,
    street TEXT NOT NULL,
    number TEXT NOT NULL,
    neighborhood TEXT NOT NULL,
    city TEXT NOT NULL,
    uf TEXT NOT NULL,
    complement TEXT,
    tracking_code TEXT,
    coupon_code TEXT,
    discount_amount NUMERIC DEFAULT 0.00 NOT NULL,
    subtotal NUMERIC DEFAULT 0.00 NOT NULL
);

-- Garantir colunas em bancos existentes
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS cep TEXT;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS tracking_code TEXT;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS coupon_code TEXT;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS discount_amount NUMERIC DEFAULT 0.00 NOT NULL;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS subtotal NUMERIC DEFAULT 0.00 NOT NULL;

-- 2. Criar a tabela de Itens do Pedido (order_items)
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    product_name TEXT NOT NULL,
    quantity INT NOT NULL,
    price NUMERIC NOT NULL
);

-- 3. Criar a tabela de Favoritos (favorites)
CREATE TABLE IF NOT EXISTS public.favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE NOT NULL,
    UNIQUE (user_id, product_id)
);

-- 4. Criar a tabela de Endereços do Cliente (client_addresses)
CREATE TABLE IF NOT EXISTS public.client_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    name TEXT NOT NULL, -- Ex: "Casa", "Trabalho"
    cep TEXT,
    street TEXT NOT NULL,
    number TEXT NOT NULL,
    neighborhood TEXT NOT NULL,
    city TEXT NOT NULL,
    uf TEXT NOT NULL,
    complement TEXT,
    is_default BOOLEAN DEFAULT false NOT NULL
);

-- 5. Criar a tabela de Cartões do Cliente (client_cards)
CREATE TABLE IF NOT EXISTS public.client_cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    cardholder_name TEXT NOT NULL,
    last_digits TEXT NOT NULL,
    brand TEXT NOT NULL,
    expiry TEXT NOT NULL
);

